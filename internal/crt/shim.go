// The FFI shim is the one place that knows C's real widths.
//
// Both backends call a foreign function the same way they call anything
// in the runtime: every argument one qword, every result one qword. C
// does not work that way — a function returning `int` leaves the upper
// half of the register undefined, and one taking `float` wants a single,
// not a double — so between the two sits a generated wrapper per symbol
// that takes the uniform shape and calls the real one with its declared
// types.
//
// Generating C for this rather than teaching each backend the widths is
// deliberate. The assembler backend would otherwise have to sign-extend,
// truncate and convert by hand, and the C backend would do the same work
// again in a second dialect, which is two chances to disagree over a
// question `cc` already answers.
//
// The real function is declared under a private name bound to the C
// symbol with an asm label. That keeps the declaration from colliding
// with a system header the runtime already includes — `sqrt` is declared
// in math.h, and redeclaring it here with our own widths would be an
// error rather than a link.

// Shim renders the wrappers a module's foreign imports need, and the
// libraries they must be linked against. Both are empty for a program
// that calls no foreign function.
func Shim(module *metals.Module) (source string, libraries []string) {
	symbols, libraries := foreignSymbols(module)
	if len(symbols) == 0 {
		return "", nil
	}

	w := &writer{layout: metals.NewLayout(module, func(string, ...any) {}), types: map[string]*metals.TypeDecl{}}
	for _, decl := range module.Types {
		w.types[decl.Name] = decl
	}

	var out strings.Builder
	out.WriteString("/* generated by gyro build: one wrapper per foreign symbol */\n")
	out.WriteString("#include <stddef.h>\n#include <stdint.h>\n")
	out.WriteString("typedef void (*gy_code)(void);\n")
	out.WriteString("extern void (*gy_flush_hook)(void);\n")
	for _, sym := range symbols {
		w.declareRecords(sym.sig)
	}
	out.WriteString(w.records.String())
	out.WriteString("\n")
	for _, sym := range symbols {
		w.writeWrapper(&out, sym.name, sym.sig)
	}
	return out.String(), libraries
}

// ShimDeclarations prototypes the wrappers for a translation unit that
// calls them but does not define them, which is the C backend's own
// output: the shim is compiled beside it rather than into it, so that
// both backends read one generated file.
func ShimDeclarations(module *metals.Module) string {
	symbols, _ := foreignSymbols(module)
	var out strings.Builder
	for _, sym := range symbols {
		params := make([]string, 0, len(sym.sig.Params)+1)
		if isRecord(sym.sig.Result) {
			// A struct result is written through a hidden first pointer,
			// which is what both backends already emit for an aggregate.
			params = append(params, "void *")
		}
		for _, param := range sym.sig.Params {
			params = append(params, uniformType(param))
		}
		result := uniformType(sym.sig.Result)
		if isRecord(sym.sig.Result) {
			result = "void"
		}
		fmt.Fprintf(&out, "%s %s(%s);\n", result, ShimSymbol(sym.name), paramList(params))
	}
	return out.String()
}

// writer carries what the struct declarations need: the module's records
// and the layout they are asserted against.
type writer struct {
	layout  *metals.Layout
	types   map[string]*metals.TypeDecl
	records strings.Builder
	named   map[string]string
}

func isRecord(t metals.Type) bool {
	named, ok := t.(*metals.Named)
	return ok && named != nil
}

type foreignSymbol struct {
	name string
	sig  *metals.FnType
}

// foreignSymbols lists a module's C imports and the libraries they come
// from, both in a stable order so the generated source is reproducible.
func foreignSymbols(module *metals.Module) (symbols []foreignSymbol, libraries []string) {
	seen := map[string]bool{}
	for _, imp := range module.Imports {
		library := metals.ExternLibrary(imp.Module)
		if library == "" {
			continue
		}
		if !seen["lib:"+library] {
			seen["lib:"+library] = true
			libraries = append(libraries, library)
		}
		for _, fn := range imp.Funcs {
			if seen[fn.Name] {
				continue
			}
			seen[fn.Name] = true
			symbols = append(symbols, foreignSymbol{name: fn.Name, sig: fn.Sig})
		}
	}
	sort.Slice(symbols, func(i, j int) bool { return symbols[i].name < symbols[j].name })
	sort.Strings(libraries)
	return symbols, libraries
}

// ShimSymbol names the wrapper a backend calls for a foreign symbol.
func ShimSymbol(name string) string { return "gy_ffi_" + name }

func (w *writer) writeWrapper(out *strings.Builder, name string, sig *metals.FnType) {
	target := ShimSymbol(name) + "_target"

	declared := make([]string, len(sig.Params))
	for i, param := range sig.Params {
		declared[i] = w.cType(param)
	}
	fmt.Fprintf(out, "extern %s %s(%s) __asm__(\"%s\");\n",
		w.cType(sig.Result), target, paramList(declared), name)

	// A struct travels as a pointer to the caller's copy, which is what
	// both backends already do with an aggregate; the wrapper is where it
	// becomes the by-value argument C's ABI wants, since `cc` knows that
	// ABI and neither backend should have to.
	var uniform []string
	if isRecord(sig.Result) {
		uniform = append(uniform, "void *gy_out")
	}
	forwarded := make([]string, len(sig.Params))
	for i, param := range sig.Params {
		uniform = append(uniform, fmt.Sprintf("%s a%d", uniformType(param), i))
		if isRecord(param) {
			forwarded[i] = fmt.Sprintf("*(const %s *)a%d", w.cType(param), i)
			continue
		}
		forwarded[i] = fmt.Sprintf("(%s)a%d", w.cType(param), i)
	}

	result := uniformType(sig.Result)
	if isRecord(sig.Result) {
		result = "void"
	}
	fmt.Fprintf(out, "%s %s(%s) {\n", result, ShimSymbol(name), paramList(uniform))

	// What the program printed so far goes out before a C library gets to
	// print: standard output is buffered on this side, and not on that one.
	out.WriteString("  if (gy_flush_hook != 0) gy_flush_hook();\n")

	call := fmt.Sprintf("%s(%s)", target, strings.Join(forwarded, ", "))
	switch {
	case sig.Result == nil:
		fmt.Fprintf(out, "  %s;\n}\n\n", call)
	case isRecord(sig.Result):
		fmt.Fprintf(out, "  *(%s *)gy_out = %s;\n}\n\n", w.cType(sig.Result), call)
	default:
		fmt.Fprintf(out, "  return (%s)%s;\n}\n\n", result, call)
	}
}

// declareRecords emits a C struct for every record in a signature, its
// members spelled the way C would spell them, with the layout asserted
// against the one both backends computed. That assert is the whole claim
// this feature makes — that a Gyro struct and a C struct are the same
// bytes — so it is checked by `cc` on every build rather than argued for.
func (w *writer) declareRecords(sig *metals.FnType) {
	for _, param := range sig.Params {
		w.cType(param)
	}
	if sig.Result != nil {
		w.cType(sig.Result)
	}
}

// recordType declares a named type the way C declares it, with the
// layout this compiler computed asserted against `cc`'s own. A union is
// declared as a union: every member at offset zero is the claim, so
// every member's offset is what gets asserted, and the size is the
// widest member's rounded to the strictest alignment.
func (w *writer) recordType(name string) string {
	if spelling, ok := w.named[name]; ok {
		return spelling
	}
	decl := w.types[name]
	if decl == nil || (decl.Record == nil && decl.Union == nil) {
		return "void *"
	}
	if w.named == nil {
		w.named = map[string]string{}
	}

	keyword, prefix := "struct", "gy_s"
	if decl.Union != nil {
		keyword, prefix = "union", "gy_u"
	}
	spelling := prefix + sanitizeName(name)
	// Published before the body is built, so a type reaching itself
	// through a pointer names one that is already declared.
	w.named[name] = spelling

	members := decl.Members()
	var body strings.Builder
	fmt.Fprintf(&body, "\ntypedef %s {", keyword)
	for index, member := range members {
		fmt.Fprintf(&body, " %s;", w.memberDecl(member.Type, memberName(member.Name, index)))
	}
	fmt.Fprintf(&body, " } %s;\n", spelling)
	fmt.Fprintf(&body, "_Static_assert(sizeof(%s) == %d, \"layout of %s\");\n",
		spelling, w.layout.Size(&metals.Named{Name: name}), name)
	for index, member := range members {
		offset := 0
		if decl.Record != nil {
			offset = w.layout.FieldOffset(decl.Record, index)
		}
		fmt.Fprintf(&body, "_Static_assert(offsetof(%s, %s) == %d, \"layout of %s\");\n",
			spelling, memberName(member.Name, index), offset, name)
	}
	w.records.WriteString(body.String())
	return spelling
}

// memberName keeps a C name that is legal and recognizable: the field's
// own when it is a plain identifier, and its index when it is not.
func memberName(name string, index int) string {
	if isCName(name) {
		return name
	}
	return fmt.Sprintf("f%d", index)
}

func isCName(name string) bool {
	for i, r := range name {
		digit := r >= '0' && r <= '9'
		letter := r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
		if !letter && !(digit && i > 0) {
			return false
		}
	}
	return name != ""
}

func sanitizeName(name string) string {
	var out strings.Builder
	for _, r := range name {
		if isCName(string(r)) || (r >= '0' && r <= '9') {
			out.WriteRune(r)
			continue
		}
		out.WriteByte('_')
	}
	return out.String()
}

func paramList(parts []string) string {
	if len(parts) == 0 {
		return "void"
	}
	return strings.Join(parts, ", ")
}

// uniformType is how a value reaches the wrapper: one qword, and the
// only distinctions that survive are float against integer, because the
// System V ABI puts them in different registers, and pointer against
// integer, because C objects to converting between the two silently.
func uniformType(t metals.Type) string {
	if t == nil {
		return "void"
	}
	switch t := t.(type) {
	case *metals.Handle, *metals.Ptr, *metals.AnyPtr:
		return "void *"
	case *metals.CodeType:
		// A generic function pointer, which is what both backends carry a
		// `code` in. C converts between function pointer types with a
		// cast and between one and `void *` with nothing to stand on, so
		// the uniform spelling has to be a function pointer.
		return "gy_code"
	case *metals.Prim:
		switch t.Kind {
		case metals.F32, metals.F64:
			return "double"
		}
	}
	// A struct arrives as a pointer to the caller's copy, which is what
	// both backends do with an aggregate; the wrapper dereferences it.
	if isRecord(t) {
		return "void *"
	}
	return "int64_t"
}

// cType is the real C type the foreign function declared, as an abstract
// declarator: what a cast or a prototype writes where no name follows.
func (w *writer) cType(t metals.Type) string { return w.declarator(t, "") }

// declarator spells a C declaration of t naming `name`, C's own way
// round rather than left to right: an array wraps the name in `[N]`, a
// function pointer wraps it in `(*name)(...)`, and everything else
// precedes it. An empty name gives the abstract form.
//
// This is what a pointer parameter needs and `cType` alone could not
// give: `int (*)[4]` and `int (*)(const void *, const void *)` are not a
// base type with a `*` glued on.
func (w *writer) declarator(t metals.Type, name string) string {
	switch t := t.(type) {
	case *metals.Ptr:
		return w.declarator(t.Elem, "*"+name)
	case *metals.ArrayOf:
		return w.declarator(t.Elem, fmt.Sprintf("%s[%d]", parenthesize(name), t.Len))
	case *metals.CodeType:
		params := make([]string, len(t.Params))
		for i, param := range t.Params {
			params[i] = w.cType(param)
		}
		// A `code` value is already the pointer, so the declarator is
		// pointer-to-function rather than function.
		inner := fmt.Sprintf("(*%s)(%s)", name, paramList(params))
		if t.Result == nil {
			return "void " + inner
		}
		return w.declarator(t.Result, inner)
	case *metals.Named:
		return spell(w.recordType(t.Name), name)
	}
	return spell(scalarCType(t), name)
}

// parenthesize binds a `*` to the name before an array or a parameter
// list takes it: `int *p[4]` is an array of pointers and `int (*p)[4]`
// is a pointer to an array, and only the second is what a `ptr<array>`
// means.
func parenthesize(name string) string {
	if strings.HasPrefix(name, "*") {
		return "(" + name + ")"
	}
	return name
}

func spell(base, name string) string {
	switch {
	case name == "":
		return base
	case strings.HasSuffix(base, "*"):
		return base + name
	}
	return base + " " + name
}

// memberDecl declares one member: what C calls this type inside a
// struct, and its name.
func (w *writer) memberDecl(t metals.Type, name string) string {
	leaf := t
	for {
		array, ok := leaf.(*metals.ArrayOf)
		if !ok {
			break
		}
		leaf = array.Elem
	}
	if prim, ok := leaf.(*metals.Prim); ok && prim.Kind == metals.Bool {
		// A bool argument is an int because C's usually is; a bool member
		// is the one byte Gyro stores.
		dims := ""
		for cursor := t; ; {
			array, ok := cursor.(*metals.ArrayOf)
			if !ok {
				break
			}
			dims += fmt.Sprintf("[%d]", array.Len)
			cursor = array.Elem
		}
		return "uint8_t " + name + dims
	}
	return w.declarator(t, name)
}

func scalarCType(t metals.Type) string {
	if t == nil {
		return "void"
	}
	if _, ok := t.(*metals.Handle); ok {
		return "void *"
	}
	prim, ok := t.(*metals.Prim)
	if !ok {
		// The verifier's boundary rules already refused everything else,
		// so this is a backend bug rather than a program's.
		return "void *"
	}
	switch prim.Kind {
	case metals.I8:
		return "int8_t"
	case metals.I16:
		return "int16_t"
	case metals.I32:
		return "int32_t"
	case metals.I64, metals.Isize:
		return "int64_t"
	case metals.U8:
		return "uint8_t"
	case metals.U16:
		return "uint16_t"
	case metals.U32:
		return "uint32_t"
	case metals.U64, metals.Usize:
		return "uint64_t"
	case metals.F32:
		return "float"
	case metals.F64:
		return "double"
	case metals.Rune:
		return "int32_t"
	case metals.Bool:
		// A function that returns a _Bool sets the low byte of the
		// register and leaves the rest as it was, so reading the result
		// as anything wider reads garbage. The prototype says _Bool and
		// the compiler reads exactly what the callee wrote.
		return "_Bool"
	}
	return "int64_t"
}
